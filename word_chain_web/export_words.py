"""
Export the word lists into words.js so the web page can load them.

    python export_words.py
    python export_words.py --allowed data/popular.txt --common data/common_short.txt
    python export_words.py --allowed data/enable1.txt   (the bigger, looser dictionary)

Run this again any time you change a word list. It writes words.js
next to this script.

Why a .js file and not .json? Browsers refuse to load a .json file
with fetch() when you open index.html straight from your computer
(a file:// address). A .js file loaded with a <script> tag works
everywhere, including GitHub Pages.
"""

from __future__ import annotations

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
WORD_LENGTH = 4


def load_words(path: str) -> set[str]:
    """Same rules as words.py in the Python version."""
    words = set()
    with open(path, encoding="utf-8") as f:
        for line in f:
            w = line.strip().lower()
            if len(w) == WORD_LENGTH and all("a" <= c <= "z" for c in w):
                words.add(w)
    return words


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--allowed", default=os.path.join(HERE, "data", "popular.txt"),
                        help="every word a player may type")
    parser.add_argument("--common", default=os.path.join(HERE, "data", "common_short.txt"),
                        help="familiar words used for start and target words")
    parser.add_argument("--out", default=os.path.join(HERE, "words.js"))
    args = parser.parse_args()

    allowed = load_words(args.allowed)
    common = load_words(args.common) & allowed   # drop junk like "html"
    # Plurals ("acts", "bags") make dull start and target words, so skip
    # words ending in a single s. Players can still TYPE them, since they
    # stay in the allowed list. Delete this line if you want them back.
    common = {w for w in common if not w.endswith("s") or w.endswith("ss")}

    data = {"allowed": sorted(allowed), "common": sorted(common)}
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("// Generated by export_words.py. Don't edit by hand.\n")
        f.write("window.WORD_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")

    size_kb = os.path.getsize(args.out) / 1024
    print(f"{len(allowed)} allowed words, {len(common)} common words -> {args.out} ({size_kb:.0f} KB)")


if __name__ == "__main__":
    main()
